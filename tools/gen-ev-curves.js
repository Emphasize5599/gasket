#!/usr/bin/env node
// Builds assets/web/evcurves-data.js from Open EV Data's ev-data.json (https://github.com/KilowattApp/open-ev-data,
// MIT License with Attribution Requirement; credited in THIRD_PARTY_NOTICES.md).
//   node tools/gen-ev-curves.js /path/to/ev-data.json
// Kept: DC curves the dataset doesn't mark as its default template, with 2+ points. Dropped: rows whose DC peak equals
// the battery size (a duplicate set of lowercase rows where the "power" is really the pack's kWh) and rows without a
// model name. The raw file isn't committed; its checksum and date go into the output.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const src=process.argv[2];if(!src){console.error('usage: node tools/gen-ev-curves.js ev-data.json');process.exit(1);}
const raw=fs.readFileSync(src),json=JSON.parse(raw),rows=[];
for(const v of json.data||[]){
  const dc=v.dc_charger||{},curve=(dc.charging_curve||[]).filter(p=>Number.isFinite(+p.percentage)&&+p.power>0);
  if(dc.is_default_charging_curve||curve.length<2||!/^[A-Z0-9]/.test(String(v.model||'')))continue;
  const battery=+v.usable_battery_size||0,peak=Math.max(...curve.map(p=>+p.power));
  if(battery&&Math.abs(peak-battery)<.05)continue;
  const pts=[];curve.slice().sort((a,b)=>a.percentage-b.percentage).forEach(p=>pts.push(Math.round(+p.percentage),Math.round(+p.power*10)/10));
  rows.push([v.brand,v.model,v.variant||'',+v.release_year||0,battery,pts]);
}
rows.sort((a,b)=>(a[0]+a[1]+a[2]).localeCompare(b[0]+b[1]+b[2])||a[3]-b[3]);
const meta={source:'Open EV Data (https://github.com/KilowattApp/open-ev-data)',updated:(json.meta||{}).updated_at||'',sha256:crypto.createHash('sha256').update(raw).digest('hex'),rows:rows.length};
const out='/* Generated by tools/gen-ev-curves.js from Open EV Data (https://github.com/KilowattApp/open-ev-data), MIT License with\n'+
  ' * Attribution Requirement. Rows: [brand, model, variant, year, usable kWh, [SOC %, kW, SOC %, kW, ...]]. Do not edit by hand. */\n'+
  '(function(root){var data={meta:'+JSON.stringify(meta)+',rows:'+JSON.stringify(rows)+'};\n'+
  'if(typeof module!=="undefined"&&module.exports)module.exports=data;else root.EVCurveData=data;})(typeof window!=="undefined"?window:globalThis);\n';
fs.writeFileSync(path.join(__dirname,'..','assets','web','evcurves-data.js'),out);
console.log('evcurves-data.js:',rows.length,'curves,',out.length,'bytes');
