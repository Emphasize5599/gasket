// Builds assets/web/counties.js: U.S. county outlines by 5-digit FIPS code, for placing National Weather Service alerts
// (which list their counties) on a route. Source: us-atlas counties-10m (U.S. Census Bureau cartographic boundaries).
//   npm i us-atlas@3 topojson-client@3   (anywhere), then:  node tools/gen-counties.js <that node_modules folder>
// Same shape as states.js: US_COUNTIES[fips] = [polygon, ...], polygon = [outer ring, holes...], ring = [lng, lat, lng, lat, ...].
// Rings are simplified to ~300 m (Douglas–Peucker, 0.003°) and rounded to 0.001° (about 100 m): plenty for "is the
// road in this county", and small enough to load only when an alert needs it.
const fs = require('fs'), path = require('path');
const mods = process.argv[2] || 'node_modules';
const topo = require(path.resolve(mods, 'us-atlas/counties-10m.json')), { feature } = require(path.resolve(mods, 'topojson-client'));
const TOL = 0.003;
/** A closed ring (first point = last): split at the point farthest from the start, simplify both halves. */
function simplify(pts) {
  if (pts.length <= 4) return pts;
  let far = 1, fd = 0;
  for (let i = 1; i < pts.length - 1; i++) { const d = Math.hypot(pts[i][0] - pts[0][0], pts[i][1] - pts[0][1]); if (d > fd) { fd = d; far = i; } }
  const a = dp(pts.slice(0, far + 1)), b = dp(pts.slice(far));
  return a.concat(b.slice(1));
}
function dp(pts) {
  if (pts.length <= 2) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let far = -1, fd = 0;
    const [ax, ay] = pts[a], [bx, by] = pts[b], dx = bx - ax, dy = by - ay, L = Math.hypot(dx, dy) || 1e-12;
    for (let i = a + 1; i < b; i++) { const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / L; if (d > fd) { fd = d; far = i; } }
    if (fd > TOL) { keep[far] = 1; stack.push([a, far], [far, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
const r3 = (v) => Math.round(v * 1000) / 1000;
const fc = feature(topo, topo.objects.counties), out = {};
let rings = 0, coords = 0;
for (const f of fc.features) {
  if (!f.geometry || !f.id) continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  out[f.id] = polys.map((poly) => poly.map((ring) => { const s = simplify(ring); rings++; coords += s.length; return [].concat(...s.map(([x, y]) => [r3(x), r3(y)])); }));
}
const js = '/* U.S. county outlines by FIPS code (U.S. Census Bureau cartographic boundaries via us-atlas, 1:10m, simplified), for placing weather alerts on a route. Generated by tools/gen-counties.js. */\nwindow.US_COUNTIES=' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'assets', 'web', 'counties.js'), js);
console.log(Object.keys(out).length + ' counties, ' + rings + ' rings, ' + coords + ' points, ' + Math.round(js.length / 1024) + ' KB');
